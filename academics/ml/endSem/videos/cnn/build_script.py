def main():
    here = Path(__file__).resolve().parent
    script, review, total, covered = {}, [], 0, set()
    for scene, lines in SCENES.items():
        script[scene] = []
        chars = sum(len(l[0]) for l in lines)
        ids = sorted({c for l in lines for c in l[2].split()})
        review += [f"## {scene}", "",
                   f"Coverage: {', '.join(ids) if ids else 'none (bridging)'}  ",
                   f"Characters: {chars:,}; about {chars / 14.5:.0f} s of speech", "",
                   "| Line | Narration | Planned visual | Coverage | Mark |", "|---|---|---|---|---|"]
        for n, line in enumerate(lines, 1):
            text, visual, cov = line[0], line[1], line[2]
            mark = {"added": "[added]", "fix": "[source fix]"}.get(line[3] if len(line) > 3 else "", "")
            assert len(text) <= 1500 and "|" not in text and "|" not in visual
            script[scene].append({"id": f"l{n:02d}", "text": text})
            review.append(f"| l{n:02d} | {text} | {visual} | {cov.replace(' ', ', ')} | {mark} |")
            covered.update(cov.split())
        review.append("")
        total += chars
    missing = sorted({f"C{i:03d}" for i in range(1, 114)} - covered)
    assert not missing, f"coverage items never spoken or shown: {missing}"
    n_lines = sum(len(v) for v in script.values())
    head = ["# Script review: CNN video (ML Lec 12)", "",
            "Generated by `build_script.py`; edit that file, not this one.", "",
            f"- Scenes: {len(script)}; lines: {n_lines}",
            f"- Total characters sent to Sarvam: {total:,}",
            f"- Sarvam cost at Rs 1 per 1,000 characters (setup guide): about Rs {total / 1000:.0f}",
            f"- Speech only, at about 14.5 characters per second: about {total / 14.5 / 60:.0f} min. Silent holds and animations add to this.",
            "- All 113 coverage items appear in at least one line (checked by the script).",
            "- [added] = not in the source (title cards, recaps, example values). [source fix] = a correction agreed in `DECISIONS.md`.",
            "- The narration writes symbols the way they are spoken (\"W 1\", \"I one one\") so the voice reads them correctly.", ""]
    (here / "script.json").write_text(json.dumps(script, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (here / "SCRIPT_REVIEW.md").write_text("\n".join(head + review), encoding="utf-8")
    print(f"{len(script)} scenes, {n_lines} lines, {total:,} characters")


if __name__ == "__main__":
    main()
